export function translate(lang: Lang, key: I18nKey, vars?: Vars): string {
  const text = lang === 'zh' ? zhDict[key] : enDict[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_m, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`
  );
}
